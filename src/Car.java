public class Car {
    int d;
    double b;
    boolean q;

    public Car(int d, double b, boolean q) {
        this.d = d;
        this.b = b;
        this.q = q;
    }

    public int getD() {
        return d;
    }

    public double getB() {
        return b;
    }

    public boolean isQ() {
        return q;
    }
}
